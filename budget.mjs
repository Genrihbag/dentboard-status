/**
 * Весь круг `check.mjs`. systemd убивает на 50 с; 10 с остаются `render.mjs` и выкладке страницы —
 * та занимает доли секунды, запас на медленный диск наблюдателя.
 */
export const ROUND_BUDGET_MS = 40_000;

/** Опрос целей — первая часть круга. Остаток (≥ 15 с) достаётся сообщениям, аватару и табло. */
export const PROBE_BUDGET_MS = 25_000;

/**
 * Один вызов Telegram. Обычно он отвечает за доли секунды; ожидание дольше значит, что ответа не
 * будет, а время круга нужнее записи страницы.
 */
export const TELEGRAM_TIMEOUT_MS = 5_000;

/** Отсчёт идёт от загрузки модуля — то есть от старта процесса, первым импортом `check.mjs`. */
const roundStartedAt = Date.now();

/** Сколько осталось от бюджета круга. Отрицательное значение — бюджет исчерпан. */
export function remainingMs(now = Date.now()) {
  return roundStartedAt + ROUND_BUDGET_MS - now;
}

/**
 * Меньше этого остатка запрос не начинается вовсе. Обрыв через миллисекунды не успевает за
 * отправкой в уже открытое соединение: Telegram выполнил бы запрос, а мы сочли бы его неудачей —
 * и табло завелось бы второе, а служебная «.» осталась бы в ленте.
 */
export const MIN_START_MS = 500;

/** Отказ «не начинали» — отличимый по имени от таймаута и от сетевой ошибки. */
export class RoundBudgetExhausted extends Error {
  constructor() {
    super("не отправляли: предел времени круга вышел");
    this.name = "RoundBudgetExhausted";
  }
}

/**
 * Сигнал отмены для одного запроса: не дольше `capMs` и не дольше остатка круга.
 *
 * ⚠️ БРОСАЕТ, ЕСЛИ ОСТАТКА МЕНЬШЕ `MIN_START_MS`. Зовётся в аргументах `fetch`, то есть до отправки:
 * исключение попадает в тот же `catch`, что и сетевой отказ, но запрос не уходит, и в журнале
 * «предел круга вышел» не сливается с «Telegram медленный».
 */
export function signalWithin(capMs, now = Date.now()) {
  const left = remainingMs(now);
  if (left < MIN_START_MS) throw new RoundBudgetExhausted();
  return AbortSignal.timeout(Math.min(capMs, left));
}
