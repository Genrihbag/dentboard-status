#!/usr/bin/env node
/**
 * НАКОПЛЕНИЕ ВРЕМЁН ОТВЕТА — образцами, без сети и без файлов.
 *
 * 🔴 ЗАЧЕМ ЭТО ПРОВЕРЯТЬ. Механизм копит молча и отдаёт числа, которые потом станут ПОРОГОМ. Его
 * ошибка не проявляется отказом: свод просто окажется не тем, и по нему назначат порог, который
 * никогда не сработает, — то есть дефект переедет в конфигурацию и станет выглядеть решением.
 *
 * Запуск: `node --test latency.test.mjs`
 */
import { test } from "node:test";
import assert from "node:assert/strict";

import { appendSample, summarise } from "./latency.mjs";

test("замеры копятся по целям и не смешиваются", () => {
  let s = {};
  s = appendSample(s, "api", 100);
  s = appendSample(s, "api", 200);
  s = appendSample(s, "сайт", 900);
  assert.deepEqual(s.api, [100, 200]);
  assert.deepEqual(s["сайт"], [900]);
});

test("окно скользит с хвоста: свежие вытесняют древние", () => {
  let s = {};
  for (const ms of [1, 2, 3, 4, 5]) s = appendSample(s, "api", ms, 3);
  assert.deepEqual(s.api, [3, 4, 5], "остаться должны ПОСЛЕДНИЕ три, а не первые");
});

// ⚠️ ПАРНЫЙ СЛУЧАЙ И САМЫЙ ЦЕННЫЙ: у неудачной пробы `ms` — время ДО ОТКАЗА, обычно таймаут.
// Подмешав его, мы получили бы «медиана выросла до 5 секунд» там, где цель просто лежала, и
// «медленно» перестало бы отличаться от «лежит». Вызывающий обязан не звать `appendSample` на
// отказе; здесь проверяется вторая линия — нечисловое и отрицательное не попадают никогда.
test("нечисловое и отрицательное не записываются", () => {
  let s = {};
  s = appendSample(s, "api", undefined);
  s = appendSample(s, "api", Number.NaN);
  s = appendSample(s, "api", -5);
  assert.equal(s.api, undefined, "хранилище должно остаться нетронутым");
});

test("исходное хранилище не мутируется", () => {
  const before = { api: [1] };
  const after = appendSample(before, "api", 2);
  assert.deepEqual(before.api, [1], "вход обязан остаться прежним");
  assert.deepEqual(after.api, [1, 2]);
});

test("свод считает перцентили по ближайшему рангу", () => {
  const s = summarise([100, 200, 300, 400, 500, 600, 700, 800, 900, 1000]);
  assert.equal(s.n, 10);
  assert.equal(s.p50, 500);
  assert.equal(s.p95, 1000);
  assert.equal(s.max, 1000);
});

test("перцентиль — наблюдённое значение, а не интерполяция", () => {
  // Между 100 и 900 интерполяция дала бы 500 — число, которого НЕ БЫЛО ни разу, и оно поехало бы
  // в документ как «замеренное».
  const s = summarise([100, 900]);
  assert.ok([100, 900].includes(s.p50), `p50 должен быть наблюдённым, получено ${s.p50}`);
});

// ⚠️ «Ноль миллисекунд» и «замеров ещё нет» — разные утверждения. Ноль читался бы как
// «мгновенно», то есть путь, не сделавший работу, вернул бы результат успешного.
test("пустое окно отдаёт null, а не ноль", () => {
  const s = summarise([]);
  assert.equal(s.n, 0);
  assert.equal(s.p50, null);
  assert.equal(s.p95, null);
  assert.equal(s.max, null);
});

test("мусор во входе не роняет свод", () => {
  const s = summarise([100, null, "300", undefined, 200]);
  assert.equal(s.n, 2, "считаться должны только числа");
  // ⚠️ ИМЕННО 100, А НЕ 200 И НЕ 150. При ближайшем ранге медиана ЧЁТНОГО числа замеров — нижнее
  // из двух средних: `ceil(0.5 × 2) = 1`. Это следствие отказа от интерполяции, а не промах —
  // 150 было бы числом, которого не наблюдали. Ожидание здесь стояло 200 и покраснело первым же
  // прогоном; неверен был тест, а не код.
  assert.equal(s.p50, 100);
});

// Положительный контроль всей затеи: на данных, похожих на боевые (150–390 мс из NL), свод
// обязан дать значения ТОГО ЖЕ порядка. Если бы он выдавал тысячи, порог по нему назначили бы
// неверный — а заметить это было бы нечем.
test("на боевом порядке величин свод даёт тот же порядок", () => {
  const real = [313, 220, 183, 214, 260, 175, 390, 205, 231, 198];
  const s = summarise(real);
  assert.ok(s.p50 >= 150 && s.p50 <= 400, `p50 вне боевого диапазона: ${s.p50}`);
  assert.equal(s.max, 390);
  assert.ok(s.p95 <= 390);
});
