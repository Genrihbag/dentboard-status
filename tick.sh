#!/usr/bin/env bash
# ОДИН КРУГ ПРОВЕРКИ: опросить цели, решить про канал и аву, при необходимости записать результат.
#
# 🔴 ЕДИНСТВЕННЫЙ ЭКЗЕМПЛЯР КРУГА — И ЭТО ГЛАВНОЕ В ФАЙЛЕ. Кругов у нас теперь два потребителя:
# таймер systemd на отдельной машине (штатный путь) и цикл `duty.sh` на машинах GitHub (запасной).
# Напиши мы логику по месту — она существовала бы в двух экземплярах и разошлась бы молча: оба
# пути отчитывались бы об успехе, а поведение зависело бы от того, кто именно проверял.
#
# ⚠️ СОСТОЯНИЕ МЕЖДУ КРУГАМИ ЖИВЁТ В ФАЙЛАХ, А НЕ В ПЕРЕМЕННЫХ. При запуске таймером каждый круг —
# отдельный процесс, и переменная оболочки не переживает его конца. Ровно на этом уже сгорел
# гистерезис авы: состояние писалось, но не сохранялось, и каждый прогон начинал с чистого листа,
# оставаясь по виду настроенным.
set -Eeuo pipefail

cd "$(dirname "$(readlink -f "$0")")"

# Как часто ЗАПИСЫВАТЬ В GIT, если ничего не менялось. Это про коммиты, а не про страницу: коммит
# на каждый круг дал бы 1440 записей в сутки и нечитаемую историю.
#
# ⚠️ К СВЕЖЕСТИ СТРАНИЦЫ ЭТОТ ПОРОГ БОЛЬШЕ НЕ ОТНОСИТСЯ — и раньше относился зря. Пока публикация
# была отправкой в `gh-pages`, страница обновлялась вместе с коммитом, то есть раз в 15 минут,
# и человек видел подпись получасовой давности при живом наблюдении раз в минуту. Свой сайт пишется
# на локальный диск и стои́т ноль, поэтому обновляется КАЖДЫЙ круг.
PERSIST_EVERY=${PERSIST_EVERY:-900}

# Отправлять ли результат в git. На своей машине это резервная копия, а не публикация, и она
# необязательна: пусто и `SITE_DIR` задан — не отправляем вовсе.
GIT_PUSH=${GIT_PUSH:-auto}
# Отметка последней записи. Рядом с данными, но НЕ в git: это состояние машины-наблюдателя, а не
# наблюдаемого — двум наблюдателям оно разное, и общий файл столкнул бы их лбами.
LAST_PERSIST_FILE=${LAST_PERSIST_FILE:-.last-persist}

# КУДА КЛАСТЬ ГОТОВУЮ СТРАНИЦУ НА ЭТОЙ МАШИНЕ. Пусто — публикуем в `gh-pages`, как раньше.
SITE_DIR=${SITE_DIR:-}

# ПУБЛИКАЦИЯ НА СВОЁМ NGINX — штатный путь с 29.08.2026.
#
# ⚠️ КОПИРОВАНИЕ ЧЕРЕЗ ВРЕМЕННЫЙ ФАЙЛ И `mv`, А НЕ ПРЯМО В МЕСТО. `mv` в пределах одной файловой
# системы атомарен: читатель получает либо старую страницу целиком, либо новую целиком. Копируй мы
# поверх — человек, открывший страницу в эту миллисекунду, увидел бы обрезанный HTML, и выглядело
# бы это как поломка сайта состояния в момент аварии, то есть в худший из возможных.
publish_local() {
  install -d "$SITE_DIR/data"
  install -m 0644 index.html "$SITE_DIR/.index.html.new"
  mv -f "$SITE_DIR/.index.html.new" "$SITE_DIR/index.html"
  install -m 0644 data/history.json "$SITE_DIR/data/.history.json.new"
  mv -f "$SITE_DIR/data/.history.json.new" "$SITE_DIR/data/history.json"
}

# ⚠️ ПУБЛИКАЦИЯ В `gh-pages` ПЛОСКИМ GIT — запасной путь, когда своего сайта нет. Одним оторванным
# коммитом: ветка не растёт, иначе за год в ней накопилось бы шестизначное число коммитов.
publish_page() {
  local dir
  dir=$(mktemp -d)
  mkdir -p "$dir/data"
  cp index.html CNAME favicon.ico icon.svg apple-icon.png "$dir/" 2> /dev/null || true
  cp data/history.json "$dir/data/" 2> /dev/null || true
  (
    cd "$dir"
    git init -q
    git checkout -q -b gh-pages
    git add -A
    git -c user.name="status-bot" -c user.email="status-bot@users.noreply.github.com" \
      commit -qm "страница состояния $(date -u +%F\ %T) UTC"
    git push -q --force "$(git -C "$OLDPWD" remote get-url origin)" gh-pages
  )
  rm -rf "$dir"
}

# Записать результат в репозиторий и опубликовать страницу. Отказ отдельного шага не валит круг:
# не сумев записать, наблюдать мы не перестаём.
persist() {
  local why=$1
  node render.mjs || echo "предупреждение: страница не собралась" >&2

  git add data/history.json data/avatar.json index.html

  # Коммит ДО подтягивания чужих правок, а не после.
  #
  # 🔴 ПОРЯДОК НАЙДЕН УЧЕНИЕМ, А НЕ ЧТЕНИЕМ. Первая редакция звала `git pull --rebase` первым — и он
  # отказывался: «cannot pull with rebase: You have unstaged changes». Это ломало бы КАЖДУЮ запись,
  # потому что `render.mjs` переписывает `index.html` (там время замера) прямо перед вызовом. Дерево
  # грязное всегда, значит отказ был бы всегда.
  if ! git diff --cached --quiet; then
    git -c user.name="status-bot" -c user.email="status-bot@users.noreply.github.com" \
      commit -qm "статус: ${why} $(date -u +%F\ %T) UTC"
  fi

  # ⚠️ СЧИТАЕМ НЕОТПРАВЛЕННЫЕ КОММИТЫ, А НЕ «ЕСТЬ ЛИ ЧТО КОММИТИТЬ». Если прошлый круг закоммитил,
  # но не смог отправить (сеть, чужой коммит), коммит остался лежать. По признаку «нечего
  # коммитить» мы бы его больше не тронули, и запись потерялась бы навсегда, выглядя при этом как
  # «изменений не было».
  local ahead
  ahead=$(git rev-list --count "@{u}..HEAD" 2> /dev/null || echo 0)
  if [ "$ahead" -eq 0 ]; then
    echo "нечего записывать (${why})"
    return 0
  fi

  # ⚠️ `--autostash` ОБЯЗАТЕЛЕН, И ЭТО НАЙДЕНО УЧЕНИЕМ. Без него `rebase` отказывается работать при
  # ЛЮБОМ постороннем изменении в дереве — «cannot pull with rebase: You have unstaged changes», —
  # а посторонним оказывается что угодно: правка скрипта на машине, недоделанный файл, случайный
  # артефакт. Наблюдатель работает без человека месяцами, и запись не должна ломаться от того, что
  # кто-то однажды тронул файл рядом.
  git pull -q --rebase --autostash || echo "предупреждение: не удалось подтянуть основную ветку" >&2
  if git push -q; then
    # `gh-pages` — только когда своего сайта нет: там публикация и есть отправка в git.
    if [ -z "$SITE_DIR" ]; then
      publish_page || echo "предупреждение: страница не опубликовалась" >&2
    fi
    date +%s > "$LAST_PERSIST_FILE"
    echo "записано (${why}), неотправленных коммитов было ${ahead}"
  else
    echo "предупреждение: не удалось отправить состояние — коммит остался, попробуем на следующем круге" >&2
  fi
}

# ⚠️ ПОЧИНКА ДЕРЕВА ПЕРЕД РАБОТОЙ — наблюдатель обязан выкарабкиваться сам.
#
# 🔴 ПОВОД, 29.08.2026: незавершённый `rebase` оставил репозиторий ВНЕ ВЕТКИ, и каждый следующий
# круг спотыкался об это навсегда — «You are not currently on a branch». Проверка при этом шла, в
# канал писалось, а страница замерла: отказ выглядел как тишина. Случилось из-за двух наблюдателей
# сразу (смена на GitHub ещё дежурила и писала в тот же репозиторий), но причина второстепенна —
# важно, что из такого состояния машина без человека не выходит НИКОГДА.
#
# Обе команды безопасны: `--abort` откатывает незаконченный rebase, `checkout` возвращает на ветку.
# Ничего чужого они не выбрасывают — только незавершённое своё.
if ! git symbolic-ref -q HEAD > /dev/null; then
  echo "предупреждение: дерево вне ветки — чиню (незавершённый rebase?)" >&2
  git rebase --abort 2> /dev/null || true
  git checkout -q main 2> /dev/null || echo "предупреждение: вернуться на main не удалось" >&2
fi

out=$(mktemp)
# Отказ круга не валит скрипт: сеть рвётся, и упавший таймер молчал бы до вмешательства человека.
# Но НЕ молча — предупреждение уходит в журнал, а «кругов ноль» отличимо от «круги идут, целей нет».
if ! GITHUB_OUTPUT="$out" node check.mjs; then
  echo "предупреждение: круг выполнен не целиком" >&2
fi

changed=$(grep -m1 '^changed=' "$out" 2> /dev/null | cut -d= -f2 || echo false)
avatar=$(grep -m1 '^avatar=' "$out" 2> /dev/null | cut -d= -f2 || echo false)
rm -f "$out"

# 🔴 СТРАНИЦА ОБНОВЛЯЕТСЯ КАЖДЫЙ КРУГ, БЕЗ ВСЯКИХ ПОРОГОВ. Замер 29.08.2026: наблюдение шло раз в
# минуту, а подпись на странице была получасовой давности — потому что публикация была привязана к
# коммиту. Владелец увидел ровно это («опять 30 мин нихуя не опрашивал») и был прав: по странице
# живое наблюдение неотличимо от мёртвого, а страница и есть то, на что смотрят.
#
# Запись на локальный диск не стои́т ничего, поэтому экономить здесь нечего и незачем.
if [ -n "$SITE_DIR" ]; then
  node render.mjs || echo "предупреждение: страница не собралась" >&2
  publish_local || echo "предупреждение: страница не выложена" >&2
fi

now=$(date +%s)
last=$(cat "$LAST_PERSIST_FILE" 2> /dev/null || echo 0)

# Отправка в git — резервная копия. Со своим сайтом она не нужна для публикации, поэтому по
# умолчанию (`auto`) при заданном SITE_DIR не делается вовсе: меньше движущихся частей, меньше
# отказов, которые надо разбирать.
if [ "$GIT_PUSH" = "auto" ] && [ -n "$SITE_DIR" ]; then
  exit 0
fi

if [ "$changed" = "true" ] || [ "$avatar" = "true" ]; then
  persist "смена состояния"
elif [ $((now - last)) -ge "$PERSIST_EVERY" ]; then
  persist "отметка наблюдения"
fi
