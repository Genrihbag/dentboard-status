#!/usr/bin/env bash
# ДЕЖУРСТВО: одна смена длиной 50 минут, проверка целей раз в минуту.
#
# 🔴 ЗАЧЕМ ЦИКЛ, А НЕ РАСПИСАНИЕ — ЗАМЕР 29.08.2026. В задании стоял `cron: */5`, то есть двенадцать
# проверок в час. По журналу за час случилась РОВНО ОДНА: расписание у GitHub «best effort» —
# запуски задерживаются, а при нагрузке отбрасываются. Владелец заметил это по странице («по-моему,
# давно не обновлялось»), и он был прав; ни один наш признак этого не показывал, потому что подпись
# обещала «каждые 5 минут» и по ней исправная работа была неотличима от почти полного молчания.
#
# Теперь крон лишь ПОДНИМАЕТ СМЕНУ, а проверяет она сама. Даже если из двенадцати выстрелов долетит
# один, покрытие останется почти сплошным.
#
# ⚠️ ЧТО ДЕЛАЕТСЯ КАЖДЫЙ КРУГ, А ЧТО РЕДКО — И ПОЧЕМУ ЭТО РАЗНЫЕ СПИСКИ.
#   · каждый круг: опрос целей, сообщение в канал при смене состояния, смена авы. Всё это НЕ требует
#     записи в репозиторий, потому что состояние живёт в рабочем каталоге смены;
#   · редко (при смене состояния либо раз в 15 минут): коммит и публикация страницы. Коммит на
#     каждый круг дал бы 700 записей в сутки и нечитаемую историю, ради обновления одной подписи.
#
# ⚠️ ОТКАЗ ОДНОГО КРУГА НЕ ПРЕКРАЩАЕТ СМЕНУ. Сеть между GitHub и РФ рвётся регулярно; смена, умершая
# от одного неудачного круга, оставила бы нас без наблюдения до следующего выстрела крона — то есть
# вернула бы ровно ту беду, ради которой цикл и заведён.
set -Eeuo pipefail

DUTY_SECONDS=${DUTY_SECONDS:-3000}   # 50 минут
INTERVAL=${INTERVAL:-60}             # круг раз в минуту
# Как часто обновлять страницу и историю, даже если ничего не менялось. Это не косметика: свежая
# подпись «Проверено …» — единственное свидетельство, что наблюдение вообще живо. Протухшая подпись
# и мёртвый монитор выглядят одинаково.
PERSIST_EVERY=${PERSIST_EVERY:-900}  # 15 минут

started=$(date +%s)
last_persist=0
rounds=0
persists=0

git config user.name "status-bot"
git config user.email "status-bot@users.noreply.github.com"

# ⚠️ СТРАНИЦА ПУБЛИКУЕТСЯ ПЛОСКИМ GIT, А НЕ ГОТОВЫМ ДЕЙСТВИЕМ. Внутри цикла шага действие вызвать
# нельзя — оно объявляется отдельным шагом, а шаг выполняется один раз. Публикация одним оторванным
# коммитом повторяет прежнее поведение (`force_orphan`): ветка `gh-pages` не растёт, иначе за год
# в ней накопилось бы шестизначное число коммитов.
publish_page() {
  local dir="/tmp/pages-$$"
  rm -rf "$dir"
  mkdir -p "$dir/data"
  cp index.html CNAME favicon.ico icon.svg apple-icon.png "$dir/" 2> /dev/null || true
  cp data/history.json "$dir/data/" 2> /dev/null || true
  (
    cd "$dir"
    git init -q
    git checkout -q -b gh-pages
    git add -A
    git -c user.name="status-bot" -c user.email="status-bot@users.noreply.github.com" \
      commit -qm "страница состояния $(date -u +%F\ %T) UTC"
    git push -q --force "https://x-access-token:${GH_TOKEN}@github.com/${GITHUB_REPOSITORY}.git" gh-pages
  )
  rm -rf "$dir"
}

# Записать результат в репозиторий и опубликовать страницу. Отказ отдельного шага не валит смену:
# не сумев записать, наблюдать мы не перестаём.
persist() {
  local why=$1
  node render.mjs || echo "::warning::страница не собралась"
  git add data/history.json data/avatar.json index.html
  # Коммит ДО подтягивания чужих правок, а не после.
  #
  # 🔴 ПОРЯДОК НАЙДЕН УЧЕНИЕМ, А НЕ ЧТЕНИЕМ. Первая редакция звала `git pull --rebase` первым — и
  # он отказывался: «cannot pull with rebase: You have unstaged changes». На боевом прогоне это
  # ломало бы КАЖДУЮ запись, потому что `render.mjs` переписывает `index.html` (там время замера)
  # прямо перед этим вызовом. Дерево грязное всегда, значит отказ был бы всегда.
  if ! git diff --cached --quiet; then
    git commit -qm "статус: ${why} $(date -u +%F\ %T) UTC"
  fi

  # ⚠️ СЧИТАЕМ НЕОТПРАВЛЕННЫЕ КОММИТЫ, А НЕ «ЕСТЬ ЛИ ЧТО КОММИТИТЬ». Разница существенна: если
  # прошлый круг закоммитил, но не смог запушить (сеть, чужой коммит), коммит остался лежать. По
  # признаку «нечего коммитить» мы бы его больше не тронули, и запись потерялась бы до конца смены,
  # выглядя при этом как «изменений не было».
  local ahead
  ahead=$(git rev-list --count "@{u}..HEAD" 2> /dev/null || echo 0)
  if [ "$ahead" -eq 0 ]; then
    echo "нечего записывать (${why})"
    return 0
  fi

  # Смена живёт 50 минут, и за это время в `main` могли попасть чужие коммиты — без `--rebase`
  # отправка отвергается. Отказ здесь не фатален: попробуем на следующем круге, коммит никуда не
  # денется.
  git pull -q --rebase origin main || echo "::warning::не удалось подтянуть main"
  if git push -q origin HEAD:main; then
    publish_page || echo "::warning::страница не опубликовалась"
    persists=$((persists + 1))
    echo "записано (${why}), неотправленных коммитов было ${ahead}"
  else
    echo "::warning::не удалось отправить состояние — коммит остался, попробуем на следующем круге"
  fi
}

echo "смена заступила: ${DUTY_SECONDS} с, круг раз в ${INTERVAL} с, запись не реже ${PERSIST_EVERY} с"

while :; do
  now=$(date +%s)
  elapsed=$((now - started))
  [ "$elapsed" -lt "$DUTY_SECONDS" ] || break

  rounds=$((rounds + 1))
  out="/tmp/probe-out-$$"
  : > "$out"

  # ⚠️ ПРОВЕРОЧНОЕ СООБЩЕНИЕ — ТОЛЬКО НА ПЕРВОМ КРУГЕ. Иначе один поставленный флаг слал бы его
  # пятьдесят раз подряд, то есть превращал бы проверку связи в рассылку.
  test_flag="false"
  [ "$rounds" -eq 1 ] && test_flag="${TEST_MESSAGE:-false}"

  # Отказ круга ловится намеренно: смена продолжается. Но НЕ молча — предупреждение видно в журнале
  # задания, а «ноль кругов» отличимо от «круги идут, целей нет».
  if ! GITHUB_OUTPUT="$out" TEST_MESSAGE="$test_flag" node check.mjs; then
    echo "::warning::круг ${rounds} не выполнен целиком — смена продолжается"
  fi

  changed=$(grep -m1 '^changed=' "$out" 2> /dev/null | cut -d= -f2 || echo false)
  avatar=$(grep -m1 '^avatar=' "$out" 2> /dev/null | cut -d= -f2 || echo false)
  rm -f "$out"

  now=$(date +%s)
  if [ "$changed" = "true" ] || [ "$avatar" = "true" ]; then
    persist "смена состояния"
    last_persist=$now
  elif [ $((now - last_persist)) -ge "$PERSIST_EVERY" ]; then
    # Плановая запись: подпись «Проверено …» обязана двигаться, иначе живой монитор выглядит мёртвым.
    persist "отметка наблюдения"
    last_persist=$now
  fi

  # Спим ОСТАТОК круга, а не фиксированный интервал: сам круг занимает от секунд до полутора минут
  # (три попытки на цель по 15 с таймаута), и фиксированный сон растянул бы сетку вдвое — ровно та
  # ошибка, что уже замерена у сторожа сети (интервал 70 с вместо 60).
  spent=$(( $(date +%s) - now ))
  rest=$((INTERVAL - spent))
  [ "$rest" -gt 0 ] && sleep "$rest"
done

# ⚠️ ПОСЛЕДНЯЯ ЗАПИСЬ ПЕРЕД УХОДОМ СМЕНЫ. Без неё результаты последних минут дежурства уехали бы
# вместе с файловой системой задания — а вместе с ними и состояние авы, из-за чего следующая смена
# начала бы отсчёт подтверждений заново.
persist "конец смены"

echo "смена сдана: кругов ${rounds}, записей ${persists}, длительность $(( $(date +%s) - started )) с"
# Ноль кругов — ОТКАЗ, а не тишина: значит смена не работала вовсе, и «нарушений не найдено» здесь
# означало бы «никто не смотрел».
if [ "$rounds" -eq 0 ]; then
  echo "::error::за смену не выполнено НИ ОДНОГО круга"
  exit 1
fi
