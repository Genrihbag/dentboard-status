#!/usr/bin/env bash
# ДЕЖУРСТВО НА МАШИНАХ GITHUB — ЗАПАСНОЙ ПУТЬ, обход кривого расписания.
#
# 🔴 ЗАЧЕМ ОН ВООБЩЕ ЕСТЬ И ПОЧЕМУ ТЕПЕРЬ ЗАПАСНОЙ. Замер 29.08.2026: `cron: */5` обещает двенадцать
# прогонов в час, по журналу случился ОДИН. Расписание у GitHub «best effort» — запуски
# задерживаются, а при нагрузке отбрасываются. Цикл внутри одного задания это обходит: смена
# дежурит 50 минут и проверяет сама.
#
# Но зависимость остаётся: пока смена не заступила, наблюдения нет. Поэтому штатным путём стал
# таймер systemd на отдельной машине (`vps/`), а это — запасной, на случай, если та машина не
# поднята.
#
# ⚠️ КРУГ ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ, А ЗОВЁТСЯ. Вся работа — в `tick.sh`, одном на оба пути. Напиши мы её
# здесь ещё раз, поведение зависело бы от того, кто проверял, и расходились бы два экземпляра молча:
# оба отчитывались бы об успехе.
#
# ⚠️ ДВА НАБЛЮДАТЕЛЯ ОДНОВРЕМЕННО — ВРЕДНО. Оба пишут в один репозиторий и оба шлют в канал: на
# смене состояния человек получит два сообщения, а история будет разъезжаться при каждом круге.
# Подняв машину, выключите это задание: `gh workflow disable "Проверка доступности"`.
set -Eeuo pipefail

cd "$(dirname "$(readlink -f "$0")")"

DUTY_SECONDS=${DUTY_SECONDS:-3000}   # 50 минут
INTERVAL=${INTERVAL:-60}             # круг раз в минуту

started=$(date +%s)
rounds=0

git config user.name "status-bot"
git config user.email "status-bot@users.noreply.github.com"

echo "смена заступила: ${DUTY_SECONDS} с, круг раз в ${INTERVAL} с"

while :; do
  now=$(date +%s)
  [ $((now - started)) -lt "$DUTY_SECONDS" ] || break
  rounds=$((rounds + 1))

  # ⚠️ ПРОВЕРОЧНОЕ СООБЩЕНИЕ — ТОЛЬКО НА ПЕРВОМ КРУГЕ. Иначе один поставленный флаг слал бы его
  # пятьдесят раз подряд, превращая проверку связи в рассылку.
  test_flag="false"
  [ "$rounds" -eq 1 ] && test_flag="${TEST_MESSAGE:-false}"

  # Отказ круга не прекращает смену: сеть между GitHub и РФ рвётся регулярно, и смена, умершая от
  # одного неудачного круга, оставила бы нас без наблюдения до следующего выстрела крона — то есть
  # вернула бы ровно ту беду, ради которой цикл заведён.
  TEST_MESSAGE="$test_flag" bash tick.sh || echo "::warning::круг ${rounds} не выполнен целиком — смена продолжается"

  # Спим ОСТАТОК круга, а не фиксированный интервал: сам круг занимает от секунд до полутора минут
  # (три попытки на цель по 15 с таймаута), и фиксированный сон растянул бы сетку — ровно та ошибка,
  # что уже замерена у сторожа сети (интервал 70 с вместо 60).
  spent=$(( $(date +%s) - now ))
  rest=$((INTERVAL - spent))
  [ "$rest" -gt 0 ] && sleep "$rest"
done

echo "смена сдана: кругов ${rounds}, длительность $(( $(date +%s) - started )) с"
# Ноль кругов — ОТКАЗ, а не тишина: значит смена не работала вовсе, и «нарушений не найдено» здесь
# означало бы «никто не смотрел».
if [ "$rounds" -eq 0 ]; then
  echo "::error::за смену не выполнено НИ ОДНОГО круга"
  exit 1
fi
