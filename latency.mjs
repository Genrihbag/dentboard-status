/**
 * НАКОПЛЕНИЕ ВРЕМЁН ОТВЕТА — чтобы порог «медленно» можно было НАЗНАЧИТЬ ПО ЗАМЕРУ.
 *
 * 🔴 ЗАЧЕМ ЗАВЕДЕНО (31.08.2026). Наблюдатель меряет время ответа каждую минуту по каждой цели —
 * 1440 замеров в сутки на цель — и НЕ СОХРАНЯЛ НИ ОДНОГО: значение писалось в `current` и
 * перезаписывалось следующим тиком, а в `events` уходили только смены состояния, без времён.
 *
 * Отсюда две дыры, и обе тихие:
 *   · «сайт стал вдвое медленнее за месяц» не имело ответа В ПРИНЦИПЕ — не по недосмотру, а
 *     потому что данных не оставалось;
 *   · задача «пересчитать порог по накопленному», записанная в разборе 29.08.2026, была
 *     НЕВЫПОЛНИМА: накапливать было нечего. Порог 3000 мс при нормальных 150–390 мс из NL
 *     означает, что «медленно» не сработает практически никогда.
 *
 * ⚠️ ХРАНИМ ОТДЕЛЬНО ОТ `history.json`, И ЭТО НЕ АККУРАТНОСТЬ. Тот файл браузеры тянут каждые
 * 30 секунд (страница состояния и точка в шапке кабинетов). Положи мы туда 2880 чисел на цель —
 * заплатили бы этим трафиком за данные, которые нужны раз в месяц. В `history.json` уходит только
 * СВОД (несколько чисел на цель), сырые замеры лежат рядом.
 */

/**
 * Сколько замеров держать на цель. 2880 — это двое суток при тике раз в минуту.
 *
 * Двое, а не месяц: порог настраивают по ТИПИЧНОМУ дню, а месячное окно смешало бы выкаты,
 * учения и аварии с обычной жизнью — и медиана перестала бы означать «как обычно».
 */
export const KEEP_SAMPLES = Number(process.env.STATUS_KEEP_SAMPLES ?? 2880);

/**
 * Добавить замер. Возвращает НОВОЕ хранилище — вызывающий сам решает, записывать ли его.
 *
 * ⚠️ ЗАПИСЫВАЮТСЯ ТОЛЬКО УСПЕШНЫЕ ОТВЕТЫ, и это решение, а не упрощение. У неудачной пробы `ms`
 * — это время ДО ОТКАЗА, то есть чаще всего таймаут: подмешав его, мы получили бы «медиана
 * выросла до 5 секунд» там, где цель просто лежала. Тогда «медленно» и «лежит» перестали бы
 * различаться — ровно та склейка, против которой порог и существует.
 */
export function appendSample(store, name, ms, keep = KEEP_SAMPLES) {
  if (!Number.isFinite(ms) || ms < 0) return store;
  const next = { ...store };
  const list = Array.isArray(next[name]) ? next[name].slice() : [];
  list.push(Math.round(ms));
  // Окно скользит с ХВОСТА: свежие замеры вытесняют древние, а не наоборот.
  next[name] = list.length > keep ? list.slice(list.length - keep) : list;
  return next;
}

/**
 * Перцентиль по ближайшему рангу. Без интерполяции намеренно: значения целые миллисекунды, а
 * интерполяция дала бы дробное число, которого НИ РАЗУ не наблюдали, — и оно поехало бы в
 * документ как «замеренное».
 */
function percentile(sorted, p) {
  if (sorted.length === 0) return null;
  const rank = Math.ceil((p / 100) * sorted.length);
  return sorted[Math.min(sorted.length - 1, Math.max(0, rank - 1))];
}

/**
 * Свод по накопленному.
 *
 * ⚠️ ПУСТОЕ ОКНО ОТДАЁТ `null`, А НЕ НОЛЬ. «Ноль миллисекунд» и «замеров ещё нет» — разные
 * утверждения, а на графике и в тексте выглядели бы одинаково, причём ноль читался бы как
 * «мгновенно». Тот же довод, по которому путь, не сделавший работу, обязан вернуть отличимое
 * значение.
 */
export function summarise(samples) {
  const list = Array.isArray(samples) ? samples.filter((v) => Number.isFinite(v)) : [];
  if (list.length === 0) return { n: 0, p50: null, p95: null, max: null };
  const sorted = list.slice().sort((a, b) => a - b);
  return {
    n: sorted.length,
    p50: percentile(sorted, 50),
    p95: percentile(sorted, 95),
    max: sorted[sorted.length - 1],
  };
}
