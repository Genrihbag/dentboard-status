#!/usr/bin/env node
/**
 * АВАТАР КАНАЛА ПО СОСТОЯНИЮ СЕРВИСОВ. Исполняется на машинах GitHub, рядом с самой проверкой.
 *
 * 🔴 ПОЧЕМУ ЗДЕСЬ, А НЕ В НАШЕМ ПРИЛОЖЕНИИ. По той же причине, по какой здесь живёт вся проверка:
 * сменить аву «сервисы недоступны» обязан тот, кто НЕ зависит от этих сервисов. Код, живущий на
 * наблюдаемой машине, в нужный момент недоступен вместе с ней — и картинка осталась бы зелёной
 * ровно тогда, когда должна стать красной. 28.08.2026 это стоило 2 ч 29 мин, в течение которых
 * внутреннее наблюдение рапортовало здоровье и было право: изнутри всё работало.
 *
 * ⚠️ ТОЛЬКО СТАТИЧНОЕ ФОТО. `setChatPhoto` в Bot API принимает поле `photo` и ничего больше:
 * анимированную аву (видео-кружок в профиле) ставит лишь официальное приложение через MTProto.
 * GIF здесь поставить нельзя — не «сложно», а нечем. Поэтому кадры лежат тремя PNG.
 *
 * ⚠️ СМЕНА ФОТО ОСТАВЛЯЕТ СЛУЖЕБНОЕ СООБЩЕНИЕ В ЛЕНТЕ КАНАЛА — подписчики видят его как пост.
 * Отсюда гистерезис: мигание одной цели не должно засорять канал. Два подряд одинаковых прогона —
 * и только тогда смена.
 */
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";

/** Где храним решение об аватаре. РЯДОМ с историей: перезапуск не должен переставлять аву впустую. */
const STATE = "data/avatar.json";

/**
 * Порог «медленно», мс — ТЕПЕРЬ ИЗМЕРЕННЫЙ, а не назначенный.
 *
 * 🔴 БЫЛО 1500 И РЕЗАЛО ПО НОРМАЛЬНОМУ РАЗБРОСУ. Владелец заметил жёлтую аву при полностью зелёных
 * сервисах — и был прав: замер по журналам прогонов (28 замеров, 29.08.2026) дал медиану **822 мс**
 * и **14 % значений выше 1500**. То есть порог срабатывал на обычной жизни, а не на проблеме.
 *
 * Разброс по целям: 624–1468 у API, 625–5783 у кабинета заказчика. Хвост — холодный старт
 * SSR-страницы Next.js плюс путь GitHub → РФ, а не отказ.
 *
 * 3000 мс — это 3,6 медианы: из 28 замеров его превысил ровно один (5783). Значение осталось в
 * конфиге: следующее уточнение придёт из накопленной истории, и менять его надо будет, не трогая
 * логику.
 */
export const SLOW_MS = Number(process.env.STATUS_SLOW_MS ?? 3000);

/**
 * Сколько целей должны отвечать медленно, чтобы это считалось проблемой.
 *
 * ⚠️ ОДНОЙ НЕ ХВАТАЕТ, И ЭТО ТА ЖЕ МЫСЛЬ, ЧТО У НЕСКОЛЬКИХ ЦЕЛЕЙ У `netwatch`: одиночное значение
 * говорит о СВОЕЙ цели, а не о системе. Холодный старт одной SSR-страницы даёт 5,8 с при том, что
 * остальные три отвечают за 700 мс, — это особенность страницы, а не проблема сервиса, и менять
 * из-за неё аву канала значит учить подписчиков не смотреть на аву.
 *
 * Две — уже общее: то, что замедляет систему (диск, база, канал), задевает всё сразу.
 */
export const SLOW_TARGETS_MIN = Number(process.env.STATUS_SLOW_TARGETS_MIN ?? 2);

/**
 * Сколько подряд прогонов с новым значением нужно, чтобы сменить аву.
 *
 * ⚠️ ДВА, А НЕ ОДИН, И ЭТО НЕ ОСТОРОЖНОСТЬ РАДИ ОСТОРОЖНОСТИ. Проверка идёт раз в пять минут, у
 * каждой цели три попытки внутри прогона; одиночный провал после этого — почти всегда сеть между
 * GitHub и РФ, а не наш отказ. Реакция на него стоила бы поста в канале и обучила бы подписчиков
 * не смотреть на аву. Цена задержки при настоящем отказе — те же пять минут, и она приемлема:
 * отказ 28.08 длился 149 минут.
 */
export const CONFIRMATIONS = Number(process.env.STATUS_CONFIRMATIONS ?? 2);

/** Кадр на каждое состояние. Файл отсутствует — отказ, а не тихая подстановка соседнего. */
const FRAME = {
  up: "avatar/status-up.png",
  slow: "avatar/status-slow.png",
  down: "avatar/status-down.png",
};

/**
 * СВОД РЕЗУЛЬТАТОВ К ОДНОМУ СОСТОЯНИЮ. Чистая функция — проверяется без сети и без Telegram.
 *
 * 🔴 КРАСНАЯ — ТОЛЬКО КОГДА ЛЕЖИТ ВСЁ (решение владельца 28.08.2026). Один отвалившийся сервис —
 * ЖЁЛТАЯ, потому что продукт при этом работает: упавший портал заказчиков не мешает лаборатории
 * принимать наряды, а упавший API — да, но это уже «всё» с точки зрения человека, который смотрит
 * на аву. Красная на каждую частную неисправность обесценила бы красную вообще: подписчик
 * перестанет отличать «не работает ничего» от «не работает одно из четырёх».
 *
 * Жёлтая, таким образом, значит «есть проблемы» и включает ДВА разных повода — часть целей не
 * ответила ЛИБО все ответили, но медленно. Для картинки это одно и то же сообщение человеку
 * («что-то не так, подробности на странице»), и разделять их значило бы завести третий кадр,
 * который ничего не добавляет.
 *
 * Порядок веток значим: «лежит всё» проверяется раньше «лежит часть».
 */
export function stateOf(results, slowMs = SLOW_MS) {
  const rows = Object.values(results);
  // Пустой вход — НЕ «всё хорошо». Ноль осмотренных целей и ноль упавших выглядят одинаково
  // только в отчёте, где их не различают; здесь различаем.
  if (rows.length === 0) return "unknown";
  const down = rows.filter((r) => !r.ok).length;
  if (down === rows.length) return "down";
  if (down > 0) return "slow";
  // Считаем МЕДЛЕННЫЕ ЦЕЛИ, а не «есть ли хоть одна». Разница видна на живых данных: одиночный
  // выброс встречается в каждом седьмом прогоне, одновременное замедление двух — нет.
  const slow = rows.filter((r) => typeof r.ms === "number" && r.ms > slowMs).length;
  if (slow >= SLOW_TARGETS_MIN) return "slow";
  return "up";
}

/**
 * РЕШЕНИЕ О СМЕНЕ — тоже чистая функция, и это главное в файле: гистерезис проверяется образцами,
 * а не наблюдением за живым каналом неделю.
 *
 * `applied` — что сейчас на аватаре, `pending`/`streak` — сколько прогонов подряд мы видим новое
 * значение. Возврат `{ next, streak, change }`: «менять» и «ещё рано» обязаны быть разными
 * значениями, а не разной интонацией лога.
 */
export function decide(prev, observed, confirmations = CONFIRMATIONS) {
  const applied = prev?.applied ?? null;
  // Неизвестное состояние аву не трогает: это «мы не смогли посмотреть», а не «стало плохо».
  if (observed === "unknown") return { next: applied, streak: 0, pending: null, change: false };

  // Наблюдаем то же, что уже стои́т, — счётчик обнуляется. Иначе редкие одиночные отклонения
  // накопились бы за сутки и однажды сменили аву без настоящего повода.
  if (observed === applied) return { next: applied, streak: 0, pending: null, change: false };

  /**
   * ПЕРВЫЙ В ЖИЗНИ ПРОГОН СТАВИТ АВУ СРАЗУ, минуя подтверждения.
   *
   * ⚠️ ЭТУ ВЕТКУ ПОЙМАЛ ТЕСТ, А НЕ ЧТЕНИЕ: комментарий про «первый прогон» стоял НИЖЕ проверки
   * `streak < confirmations`, то есть до него не доходило — при пустом состоянии первый прогон
   * честно ждал второго. Читалось как реализованное правило, работало как его отсутствие. Цена:
   * на канале до второго прогона висел бы кадр, не отвечающий ни одному состоянию, а молчание
   * выглядело бы как «всё хорошо».
   */
  if (applied === null) return { next: observed, streak: 0, pending: null, change: true };

  const streak = (prev?.pending === observed ? (prev?.streak ?? 0) : 0) + 1;
  if (streak < confirmations) return { next: applied, streak, pending: observed, change: false };

  return { next: observed, streak: 0, pending: null, change: true };
}

/** Прочитать сохранённое решение. Отсутствие файла — законное «ещё не ставили». */
export function loadState() {
  if (!existsSync(STATE)) return { applied: null, pending: null, streak: 0 };
  try {
    return JSON.parse(readFileSync(STATE, "utf8"));
  } catch {
    // Битый файл — не повод падать: хуже потерять проверку целиком, чем один раз переставить аву.
    // Но и молчать нельзя — иначе «состояние сброшено» неотличимо от «состояние такое».
    console.warn(`[аватар] ${STATE} не разобрался — считаю, что аву ещё не ставили`);
    return { applied: null, pending: null, streak: 0 };
  }
}

/**
 * Различаются ли ЗНАЧИМЫЕ поля решения. Отметка времени намеренно не в счёт: она меняется каждым
 * прогоном, и по ней «состояние тронули» было бы истиной всегда.
 */
export function stateDiffers(a, b) {
  const norm = (x) => ({
    applied: x?.applied ?? null,
    pending: x?.pending ?? null,
    streak: Number(x?.streak ?? 0),
  });
  const [p, q] = [norm(a), norm(b)];
  return p.applied !== q.applied || p.pending !== q.pending || p.streak !== q.streak;
}

/**
 * Записать решение. Возвращает `true`, если ЗНАЧИМОЕ содержимое изменилось, — по этому признаку
 * задание решает, коммитить ли файл.
 *
 * 🔴 БЕЗ ЭТОГО ПРИЗНАКА ГИСТЕРЕЗИС НЕ РАБОТАЛ ВОВСЕ. Найдено 29.08.2026 по вопросу владельца
 * «почему фото канала не меняется»; в репозитории лежало состояние `applied: null` при
 * `streak: 2`, а журналы показывали смену кадра почти на каждом прогоне — то up, то slow.
 *
 * Причина: файл коммитился ТОЛЬКО когда менялось состояние истории, то есть когда цель падала или
 * поднималась. Смена авы по медленным ответам историю не меняет — значит `data/avatar.json` не
 * коммитился вовсе. Задание GitHub умирает вместе с файловой системой, следующий прогон брал из
 * репозитория старую копию с `applied: null` и попадал в ветку «первый прогон — ставим сразу».
 * Ава переставлялась каждый прогон, подтверждения не копились никогда, а по виду всё работало.
 *
 * ⚠️ ПРЕДУПРЕЖДЕНИЕ ОБ ЭТОМ БЫЛО ЗАПИСАНО В САМОМ ЗАДАНИИ ДОСЛОВНО («гистерезис не срабатывал бы
 * НИКОГДА, оставаясь по виду настроенным») — и условие строкой ниже его вызывало. Решение
 * записанное, прочитанное и не исполненное.
 */
export function saveState(state) {
  const before = loadState();
  mkdirSync("data", { recursive: true });
  writeFileSync(STATE, `${JSON.stringify({ ...state, updatedAt: new Date().toISOString() }, null, 2)}\n`);
  return stateDiffers(before, state);
}

/**
 * Поставить фото канала. Возвращает `true`, если Telegram принял.
 *
 * ⚠️ НИКАКИХ ПОВТОРОВ ВНУТРИ ОДНОГО ПРОГОНА. Прогон идёт каждые пять минут — это и есть повтор,
 * причём с заново измеренным состоянием. Цикл ретраев внутри означал бы, что мы держим задание
 * GitHub и упорно ставим картинку, про которую уже, возможно, неправда.
 */
export async function setChatPhoto(state, protectedIds = []) {
  const token = process.env.TELEGRAM_BOT_TOKEN;
  const chat = process.env.TELEGRAM_CHAT_ID;
  if (!token || !chat) {
    console.log("[аватар] TELEGRAM_BOT_TOKEN / TELEGRAM_CHAT_ID не заданы — фото не меняем");
    return false;
  }
  const path = FRAME[state];
  if (!path || !existsSync(path)) {
    // Отказ НАЗЫВАЕТ файл: подстановка соседнего кадра означала бы врать про состояние картинкой.
    console.error(`[аватар] нет кадра для состояния «${state}» (ожидался ${path})`);
    return false;
  }

  const form = new FormData();
  form.append("chat_id", chat);
  form.append("photo", new Blob([readFileSync(path)], { type: "image/png" }), path.split("/").pop());

  const res = await fetch(`https://api.telegram.org/bot${token}/setChatPhoto`, { method: "POST", body: form });
  const payload = await res.json().catch(() => ({}));
  if (payload.ok) {
    console.log(`[аватар] поставлен кадр «${state}» (${path})`);
    await sweepServiceMessage(token, chat, protectedIds);
    return true;
  }
  // Причина печатается СЛОВАМИ Telegram: «бот не админ» и «нет права менять профиль» лечатся
  // по-разному, а «не получилось» не лечится никак.
  console.error(`[аватар] Telegram отказал: ${payload.description ?? res.status}`);
  return false;
}

/**
 * УБРАТЬ СЛУЖЕБНЫЙ ПОСТ «фото канала изменено».
 *
 * 🔴 ЗАЧЕМ. Смена аватара оставляет в ленте служебное сообщение, и подписчики видят его как пост.
 * Канал заводился ради редких сообщений о сбоях; пост на каждую смену цвета превращает его в
 * шумную ленту — а шум учит пролистывать, и первым пролистают настоящий сбой.
 *
 * ⚠️ ПОЧЕМУ ТАК СТРАННО, А НЕ «УДАЛИТЬ ПО ID». Потому что id взять неоткуда: `setChatPhoto`
 * возвращает `true`, а не сообщение; `getUpdates` боту с установленным вебхуком отвечает `409`.
 * Поэтому id вычисляется: шлём собственное короткое сообщение (его id известен) и удаляем ДВА —
 * своё и предыдущее. Служебное стоит ровно перед нашим, потому что между ними ничего не успевает
 * произойти: в этот канал пишет только бот.
 *
 * ⚠️ ГРАНИЦА ПРИЁМА НАЗВАНА ЧЕСТНО: если в тот же миг в канал напишет человек, удалится ЕГО
 * сообщение вместо служебного. Риск принят осознанно — канал служебный, людей-авторов в нём нет.
 * Если появятся, эту уборку надо будет снять, а не «улучшить»: угадывание чужого id безопаснее не
 * становится.
 *
 * 🔴 `protectedIds` ЗАВЕДЁН 30.08.2026 ВМЕСТЕ С ТАБЛО — И ЭТО НЕ ПЕРЕСТРАХОВКА. С появлением
 * закреплённого табла «в канал пишет только бот» перестало означать «между служебным сообщением и
 * нашим щупом ничего нет»: пишет тот же бот, и его пост может оказаться ровно тем `id - 1`,
 * который уборка сносит вслепую. Тогда механизм удалял бы собственное табло, следующий круг
 * заводил бы новое, и канал наполнялся бы табличками — причём каждая отдельная итерация выглядела
 * бы исправной работой.
 *
 * НИКОГДА НЕ БРОСАЕТ и не влияет на исход смены аватара: ава уже поставлена, и неудача уборки —
 * косметика, которая не имеет права утащить за собой запись состояния.
 */
async function sweepServiceMessage(token, chat, protectedIds = []) {
  try {
    const probe = await fetch(`https://api.telegram.org/bot${token}/sendMessage`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      // Текст виден доли секунды; точка — чтобы не мелькало слово, которое кто-то успеет прочесть.
      body: JSON.stringify({ chat_id: chat, text: ".", disable_notification: true }),
    });
    const sent = await probe.json().catch(() => ({}));
    const id = sent?.result?.message_id;
    if (!id) {
      console.log(`[аватар] служебный пост не убран: ${sent.description ?? "нет message_id"}`);
      return;
    }
    const drop = async (messageId) => {
      const r = await fetch(`https://api.telegram.org/bot${token}/deleteMessage`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ chat_id: chat, message_id: messageId }),
      });
      const d = await r.json().catch(() => ({}));
      return Boolean(d.ok);
    };
    const mine = await drop(id);
    // Защищённый номер НЕ трогаем и говорим об этом: молчаливый пропуск читался бы как «служебное
    // сообщение убрано», а оно осталось — это разные состояния канала.
    const guarded = protectedIds.filter((x) => Number.isInteger(x)).includes(id - 1);
    if (guarded) {
      console.log(`[аватар] уборка ленты: №${id - 1} — это табло, не трогаю (служебный пост остался)`);
      return;
    }
    const service = await drop(id - 1);
    // Печатается ИСХОД КАЖДОГО удаления: «убрано» и «не смогли» иначе выглядят одинаково — тишиной,
    // а не смогли мы, скорее всего, из-за отсутствия права удалять сообщения у бота.
    console.log(
      `[аватар] уборка ленты: своё сообщение ${mine ? "удалено" : "НЕ удалено"}, ` +
        `служебное ${service ? "удалено" : "НЕ удалено (нужно право «Удаление сообщений»)"}`,
    );
  } catch (e) {
    console.log(`[аватар] уборка ленты не удалась: ${e instanceof Error ? e.message : String(e)}`);
  }
}

/**
 * Свести всё вместе: посмотреть на результаты, решить, при необходимости — поставить.
 *
 * ⚠️ СОСТОЯНИЕ СОХРАНЯЕТСЯ ТОЛЬКО ПОСЛЕ УСПЕХА `setChatPhoto`. Запиши мы решение до отправки —
 * неудача Telegram (сеть, лимит, снятое право) осталась бы записанной как сделанная, и следующий
 * прогон не повторил бы попытку: ава осталась бы прежней НАВСЕГДА, а файл утверждал бы обратное.
 * Счётчик подтверждений при этом сохраняется всегда — он про наблюдение, а не про отправку.
 */
export async function syncAvatar(results, { protectedIds = [] } = {}) {
  const observed = stateOf(results);
  const prev = loadState();
  const d = decide(prev, observed);

  if (!d.change) {
    const persisted = saveState({ applied: prev.applied ?? null, pending: d.pending, streak: d.streak });
    console.log(
      `[аватар] состояние «${observed}», на аве «${prev.applied ?? "—"}»` +
        (d.pending ? `, подтверждений ${d.streak} из ${CONFIRMATIONS}` : ", менять нечего"),
    );
    return { changed: false, state: prev.applied ?? null, observed, persisted };
  }

  const ok = await setChatPhoto(d.next, protectedIds);
  const persisted = ok
    ? saveState({ applied: d.next, pending: null, streak: 0 })
    : saveState({ applied: prev.applied ?? null, pending: observed, streak: CONFIRMATIONS });
  return { changed: ok, state: ok ? d.next : (prev.applied ?? null), observed, persisted };
}
